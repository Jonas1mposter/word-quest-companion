BEGIN;
DO $$
DECLARE p public.profiles; s jsonb; v jsonb; f jsonb; q public.roguelike_questions; rid uuid; i integer; before_coins integer; before_rank text; caught boolean; skill text; expected integer; day_used integer;
BEGIN
 SELECT * INTO STRICT p FROM public.profiles WHERE grade=7 AND (banned_until IS NULL OR banned_until<=now()) AND NOT EXISTS(SELECT 1 FROM public.roguelike_runs r WHERE r.profile_id=profiles.id AND r.phase IN ('route','combat','skill')) LIMIT 1;
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',p.user_id,'role','authenticated')::text,true);
 before_coins:=p.coins; before_rank:=p.rank_tier;
 IF has_function_privilege('anon','public.rogue_action(text,uuid,integer,text,integer)','EXECUTE') OR has_function_privilege('authenticated','public.rogue_view(uuid)','EXECUTE') OR has_table_privilege('authenticated','public.roguelike_questions','SELECT') THEN RAISE EXCEPTION 'Private access leaked'; END IF;
 s:=public.rogue_action('start'); rid:=(s->>'id')::uuid;
 IF jsonb_array_length(s->'routes')<>3 OR (SELECT ends_at-started_at FROM public.roguelike_runs WHERE id=rid)<>interval '8 minutes' THEN RAISE EXCEPTION 'Eight minute / three routes rule failed'; END IF;
 IF public.rogue_action('start')->>'id'<>rid::text THEN RAISE EXCEPTION 'Duplicate active run'; END IF;
 UPDATE public.roguelike_runs SET routes='["rest","event","battle"]',hp=30 WHERE id=rid;
 s:=public.rogue_action('route',rid,0,'rest');
 IF (s->>'hp')::integer<>52 OR s->'routes' ? 'rest' OR s->'routes' ? 'event' THEN RAISE EXCEPTION 'Rest one-use failed'; END IF;
 caught:=false; BEGIN PERFORM public.rogue_action('route',rid,1,'rest'); EXCEPTION WHEN OTHERS THEN caught:=true; END;
 IF NOT caught THEN RAISE EXCEPTION 'Repeated rest accepted'; END IF;
 s:=public.rogue_action('route',rid,1,'battle');
 q:=NULL; SELECT * INTO q FROM public.roguelike_questions WHERE run_id=rid AND idx=0;
 IF jsonb_array_length(q.options)<>4 OR NOT(q.options ? q.answer) OR (s->'question') ? 'answer' OR (s->'question') ? 'target' THEN RAISE EXCEPTION 'Issued privacy/options failed'; END IF;
 UPDATE public.roguelike_questions SET created_at=now()-interval '2 seconds' WHERE run_id=rid;
 s:=public.rogue_action('answer',rid,2,q.answer,0); f:=s->'feedback'; s:=s->'state';
 IF (f->>'damage')::integer<>8 OR (s->>'enemyHp')::integer<>16 THEN RAISE EXCEPTION 'Correct answer attack failed'; END IF;
 v:=public.rogue_action('answer',rid,2,q.answer,0);
 IF v->'state'->>'answered'<>'1' OR v->'feedback'->>'damage'<>'8' THEN RAISE EXCEPTION 'Answer retry not idempotent'; END IF;
 caught:=false; BEGIN PERFORM public.rogue_action('answer',rid,2,'changed',0); EXCEPTION WHEN OTHERS THEN caught:=true; END;
 IF NOT caught THEN RAISE EXCEPTION 'Changed retry accepted'; END IF;
 caught:=false; BEGIN PERFORM public.rogue_action('answer',rid,3,'skipped',8); EXCEPTION WHEN OTHERS THEN caught:=true; END;
 IF NOT caught THEN RAISE EXCEPTION 'Question skip accepted'; END IF;
 SELECT * INTO q FROM public.roguelike_questions WHERE run_id=rid AND idx=1;
 UPDATE public.roguelike_questions SET created_at=now()-interval '2 seconds' WHERE run_id=rid AND idx=1;
 s:=public.rogue_action('answer',rid,3,(SELECT value FROM jsonb_array_elements_text(q.options) WHERE value<>q.answer LIMIT 1),1)->'state';
 IF (s->>'hp')::integer<>42 OR s->>'streak'<>'0' THEN RAISE EXCEPTION 'Wrong answer damage failed'; END IF;
 SELECT * INTO q FROM public.roguelike_questions WHERE run_id=rid AND idx=2;
 IF q.kind<>'listening' OR q.prompt<>'' THEN RAISE EXCEPTION 'Listening issuance failed'; END IF;
 UPDATE public.roguelike_runs SET skills='{"healing":1,"echo":1}',hp=30 WHERE id=rid;
 UPDATE public.roguelike_questions SET created_at=now()-interval '2 seconds' WHERE run_id=rid AND idx=2;
 s:=public.rogue_action('answer',rid,4,q.answer,2); f:=s->'feedback'; s:=s->'state';
 IF (f->>'damage')::integer<>11 OR (f->>'healing')::integer<>4 OR (s->>'hp')::integer<>34 THEN RAISE EXCEPTION 'Listening build failed'; END IF;
 UPDATE public.roguelike_runs SET skills='{"combo":2,"power":1}',streak=3 WHERE id=rid;
 SELECT * INTO q FROM public.roguelike_questions WHERE run_id=rid AND idx=3;
 UPDATE public.roguelike_questions SET created_at=now()-interval '2 seconds' WHERE run_id=rid AND idx=3;
 s:=public.rogue_action('answer',rid,5,q.answer,3); f:=s->'feedback'; s:=s->'state';
 IF (f->>'damage')::integer<>16 OR s->>'phase'<>'skill' OR jsonb_array_length(s->'offers')<>3 THEN RAISE EXCEPTION 'Combo / skill offer failed'; END IF;
 skill:=s->'offers'->>0;
 s:=public.rogue_action('skill',rid,6,skill);
 IF s->>'floor'<>'2' OR (s->'skills'->>skill)::integer<1 THEN RAISE EXCEPTION 'Skill progression failed'; END IF;
 UPDATE public.roguelike_runs SET phase='route',routes='["elite"]',skills='{"ward":1,"armor":2}',hp=60 WHERE id=rid;
 s:=public.rogue_action('route',rid,7,'elite');
 SELECT * INTO q FROM public.roguelike_questions WHERE run_id=rid AND idx=4;
 UPDATE public.roguelike_questions SET created_at=now()-interval '2 seconds' WHERE run_id=rid AND idx=4;
 s:=public.rogue_action('answer',rid,8,(SELECT value FROM jsonb_array_elements_text(q.options) WHERE value<>q.answer LIMIT 1),4)->'state';
 IF s->>'hp'<>'60' THEN RAISE EXCEPTION 'First mistake ward failed'; END IF;
 SELECT * INTO q FROM public.roguelike_questions WHERE run_id=rid AND idx=5;
 UPDATE public.roguelike_questions SET created_at=now()-interval '2 seconds' WHERE run_id=rid AND idx=5;
 s:=public.rogue_action('answer',rid,9,(SELECT value FROM jsonb_array_elements_text(q.options) WHERE value<>q.answer LIMIT 1),5)->'state';
 IF s->>'hp'<>'50' THEN RAISE EXCEPTION 'Armor / ward once failed'; END IF;
 UPDATE public.roguelike_runs SET enemy_hp=1,skills='{}' WHERE id=rid;
 SELECT * INTO q FROM public.roguelike_questions WHERE run_id=rid AND idx=6;
 UPDATE public.roguelike_questions SET created_at=now()-interval '2 seconds' WHERE run_id=rid AND idx=6;
 s:=public.rogue_action('answer',rid,10,q.answer,6)->'state'; skill:=s->'offers'->>0;
 s:=public.rogue_action('skill',rid,11,skill);
 IF s->'skills'->>skill<>'2' THEN RAISE EXCEPTION 'Elite two-level reward failed'; END IF;
 PERFORM public.rogue_action('abandon',rid,12);
 IF (SELECT coins FROM public.roguelike_runs WHERE id=rid)<>0 THEN RAISE EXCEPTION 'Abandon rewards'; END IF;
 -- Play complete five-floor runs using real issued answers, no permanent writes.
 SELECT coalesce(sum(coins),0) INTO day_used FROM public.roguelike_rewards WHERE profile_id=p.id AND day=(now() AT TIME ZONE 'Asia/Shanghai')::date;
 FOR i IN 1..5 LOOP
  s:=public.rogue_action('start'); rid:=(s->>'id')::uuid;
  UPDATE public.roguelike_runs SET started_at=now()-interval '1 minute' WHERE id=rid;
  LOOP
   IF s->>'phase'='route' THEN
    UPDATE public.roguelike_runs SET routes=CASE WHEN floor=5 THEN '["boss"]'::jsonb ELSE '["battle","elite","rest"]'::jsonb END WHERE id=rid;
    s:=public.rogue_action('route',rid,(s->>'version')::integer,CASE WHEN s->>'floor'='5' THEN 'boss' WHEN s->>'floor'='1' THEN 'elite' ELSE 'battle' END);
   ELSIF s->>'phase'='skill' THEN s:=public.rogue_action('skill',rid,(s->>'version')::integer,s->'offers'->>0);
   ELSIF s->>'phase'='combat' THEN
    SELECT * INTO q FROM public.roguelike_questions WHERE run_id=rid AND idx=(s->>'answered')::integer;
    UPDATE public.roguelike_questions SET created_at=now()-interval '2 seconds' WHERE run_id=rid AND idx=q.idx;
    s:=public.rogue_action('answer',rid,(s->>'version')::integer,q.answer,q.idx)->'state';
   ELSE EXIT; END IF;
  END LOOP;
  IF s->>'phase'<>'won' OR (s->>'answered')::integer<10 OR s->>'floor'<>'5' THEN RAISE EXCEPTION 'Five-floor real-answer run failed'; END IF;
  expected:=least(35,greatest(0,120-day_used)); day_used:=day_used+expected;
  IF (s->>'coins')::integer<>expected THEN RAISE EXCEPTION 'Completion/elite/daily cap reward failed'; END IF;
  PERFORM public.rogue_action('state',rid);
  IF (SELECT count(*) FROM public.roguelike_rewards WHERE run_id=rid)<>1 THEN RAISE EXCEPTION 'Duplicate reward'; END IF;
 END LOOP;
 IF (SELECT coins FROM public.profiles WHERE id=p.id)-before_coins<>(SELECT sum(coins) FROM public.roguelike_rewards WHERE profile_id=p.id AND created_at>=now()) THEN RAISE EXCEPTION 'Credit mismatch'; END IF;
 IF (SELECT rank_tier FROM public.profiles WHERE id=p.id)<>before_rank OR day_used<>120 THEN RAISE EXCEPTION 'Rank or cap changed'; END IF;
 -- Timeout and empty participation pay zero, foreign users cannot read a run.
 s:=public.rogue_action('start'); rid:=(s->>'id')::uuid;
 UPDATE public.roguelike_runs SET ends_at=now()-interval '1 second' WHERE id=rid;
 s:=public.rogue_action('state',rid);
 IF s->>'phase'<>'lost' OR s->>'coins'<>'0' THEN RAISE EXCEPTION 'Empty timeout payout'; END IF;
 PERFORM set_config('request.jwt.claims','{"sub":"00000000-0000-0000-0000-000000000001","role":"authenticated"}',true);
 caught:=false; BEGIN PERFORM public.rogue_action('state',rid); EXCEPTION WHEN OTHERS THEN caught:=true; END;
 IF NOT caught THEN RAISE EXCEPTION 'Unauthorized run access'; END IF;
 RAISE NOTICE 'Roguelike: route, skills, real issued answers, five floors, rewards, cap, ordering, privacy, retries and expiry passed';
END $$;
ROLLBACK;